#!/usr/bin/env node
// PreToolUse (Edit|Write|MultiEdit|NotebookEdit): protect files Claude must not change.
import path from 'node:path';
import { readInput, block, projectDir, git, relPath } from './lib.mjs';

const input = await readInput();
const filePath = input?.tool_input?.file_path || input?.tool_input?.notebook_path;
if (!filePath) process.exit(0);

const root = projectDir(input);
const rel = relPath(filePath, root);
const base = path.posix.basename(rel);

// 1. Secrets
if (/^\.env(\..+)?$/.test(base) && base !== '.env.example') {
  block(`${rel} holds secrets. Document variables in .env.example instead; the user edits .env themselves.`);
}

// 2. Generated types
if (rel === 'src/types/database.ts') {
  block('src/types/database.ts is generated. Run `npm run db:types` instead of editing it.');
}

// 3. Native folders (CNG — configure via app.config.ts / config plugins)
if (rel.startsWith('ios/') || rel.startsWith('android/')) {
  block('Native folders are generated by Expo prebuild. Use app.config.ts or a config plugin.');
}

// 4. Migrations already on main are append-only
if (rel.startsWith('supabase/migrations/')) {
  const onMain = git(['cat-file', '-e', `main:${rel}`], root) !== null;
  if (onMain) {
    block(`${rel} is already on main. Migrations are append-only — create a new one with /db-migration <name>.`);
  }
}

process.exit(0);
